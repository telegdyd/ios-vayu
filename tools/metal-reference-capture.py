#!/usr/bin/env python3
"""Run gl_reference via sweetd, retrieve Mesa RD files and write a hash manifest.

Run from the repository root on Windows after uploading userland/obj/gl_reference
to /private/var/tmp/gl_reference. Captures stay under ignored logs/ by default.
Only files generated by these invocations are collected (directory delta).
"""
import argparse
import gzip
import hashlib
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
CLIENT = ROOT / 'devices/poco-x3-pro/tools/sweet-sh.py'
CASES = ('clear', 'texture', 'mrt', 'blend', 'compute')


def remote(*args):
    result = subprocess.run([sys.executable, str(CLIENT), *args],
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE, cwd=ROOT)
    if result.returncode:
        raise RuntimeError((result.stdout + result.stderr).decode(errors='replace'))
    # sweet-sh adds one newline after the raw payload before returning status.
    if not result.stdout.endswith(b'\n'):
        raise RuntimeError('missing sweet-sh payload terminator')
    return result.stdout[:-1]


def files():
    listing = remote('ls', '/private/var/tmp/').decode()
    return {line.split()[-1]: int(line.split()[-2]) for line in listing.splitlines()
            if line.split() and line.split()[-1].startswith('metal4_')
            and line.split()[-1].endswith('.rd')}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'logs/metal-step4')
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    if (args.output / 'manifest.json').exists():
        parser.error('choose a new output directory; an existing run is preserved')
    manifest = []
    for case in CASES:
        before = files()
        output = remote('/private/var/tmp/gl_reference', case)
        (args.output / (case + '.log')).write_bytes(output)
        print(output.decode(), flush=True)
        if ('gl_reference: PASS ' + case).encode() not in output:
            raise RuntimeError('missing PASS')
        after = files()
        generated = sorted(name for name in set(after) - set(before)
                           if name.startswith('metal4_' + case + '_'))
        if not generated:
            raise RuntimeError('no new RD captures for ' + case)
        for name in generated:
            data = remote('cat', '/private/var/tmp/' + name)
            if len(data) != after[name]:
                raise RuntimeError('capture length mismatch: ' + name)
            # These .rd files contain gzip data; validate CRC and complete stream.
            raw = gzip.decompress(data)
            (args.output / name).write_bytes(data)
            manifest.append(dict(case=case, file=name, bytes=len(data),
                                 uncompressed_bytes=len(raw),
                                 sha256=hashlib.sha256(data).hexdigest()))
        print(case + ': retrieved ' + str(len(generated)) + ' captures', flush=True)
    (args.output / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')


if __name__ == '__main__':
    main()
